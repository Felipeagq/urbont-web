export type Translations = typeof translations.en;

interface LanguageContextType {
  lang: Lang;
  t: Translations;
  setLang: (lang: Lang) => void;
}

const LanguageContext = createContext<LanguageContextType>({
  lang: "en",
  t: translations.en,
  setLang: () => {},
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem("urbont-lang") as Lang | null;
      if (stored && ["en", "es", "zh", "fr", "pt"].includes(stored)) return stored;
      return "en";
    } catch {
      return "en";
    }
  });

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try { localStorage.setItem("urbont-lang", next); } catch {}
  }, []);

  return (
    <LanguageContext.Provider value={{ lang, t: translations[lang] as unknown as Translations, setLang }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
